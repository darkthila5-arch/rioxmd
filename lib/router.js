import { BOT_NAME, MAX_MSG_AGE_S, OWNER_LIDS, OWNER_NUMBER, PREFIX, USE_BUTTONS, cooldowns, jidNum } from './config.js';
import { getText, unwrapMessage } from './text.js';
import { REACTIONS, react, say } from './card.js';
import { getMode } from './storage.js';

import { registry } from '../commands/index.js';
// Results people copy and paste are sent exactly as they are (no bold added).
const RAW_REPLY = new Set(['password', 'b64', 'unb64', 'base64', 'binary', 'unbinary', 'morse', 'fancy', 'upside', 'reverse', 'mock', 'clap', 'qr']);
/* ---------- command router ---------- */
// Finds the command in the registry (see commands/index.js) and runs it.
// To add a command you do NOT edit this file: add it to a file in commands/.
export async function handleMessage(sock, msg, sessionId) {
  if (!msg.message) return;
  const jid = msg.key.remoteJid;
  if (!jid || jid === 'status@broadcast' || jid.endsWith('@newsletter')) return;

  const ts = Number(msg.messageTimestamp || 0);
  if (ts && Date.now() / 1000 - ts > MAX_MSG_AGE_S) return;

  const text = getText(msg).trim();
  const rawMsg = unwrapMessage(msg.message);
  if (!msg.key.fromMe && (rawMsg.interactiveResponseMessage || rawMsg.buttonsResponseMessage || rawMsg.templateButtonReplyMessage || rawMsg.listResponseMessage)) {
    // Diagnostic: shows in the logs exactly what WhatsApp sent when someone tapped a button (card buttons included).
    console.log('Button tap:', JSON.stringify({ text: text.slice(0, 160), raw: rawMsg.interactiveResponseMessage || rawMsg.buttonsResponseMessage || rawMsg.templateButtonReplyMessage || rawMsg.listResponseMessage }).slice(0, 500));
  }
  if (!text) return;

  const name = msg.pushName || 'User';
  const footer = USE_BUTTONS ? `${BOT_NAME} • Tap a button` : `${BOT_NAME} • Powered by Rio Editz`;
  let commandText = text;
  if (!commandText.startsWith(PREFIX)) {
    if (!msg.key.fromMe && /^(menu|help|alive)$/i.test(commandText)) commandText = PREFIX + commandText.toLowerCase();
    else { if (rawMsg.interactiveResponseMessage || rawMsg.buttonsResponseMessage) console.log('Button tap ignored (text does not start with the prefix):', text.slice(0, 120)); return; }
  }

  const [rawCommand, ...args] = commandText.slice(PREFIX.length).trim().split(/\s+/);
  const command = (rawCommand || '').toLowerCase();
  if (!command) return;

  const now = Date.now();
  const key = `${sessionId}:${jid}:${command}:${args[0] || ''}`;
  if (cooldowns.has(key) && now - cooldowns.get(key) < 700) return;
  cooldowns.set(key, now);

  const reply = (t) => say(sock, jid, t, msg, RAW_REPLY.has(command) ? { raw: true } : {});

  // Who sent this? "owner" = the linked account itself, OWNER_NUMBER or OWNER_LID. "admin" = OWNER_NUMBER / OWNER_LID only (affects the whole server).
  // WhatsApp may show the sender as a LID (123@lid) instead of a phone number, so every id we can find for the sender is checked
  // (the chat id, the participant, their phone-number twins "...Alt", and the LID -> number table when this Baileys has one).
  const senderJids = [msg.key.fromMe ? sock.user?.id : null, msg.key.participant, msg.key.participantAlt, ...(jid.endsWith('@g.us') ? [] : [jid, msg.key.remoteJidAlt])].filter(Boolean);
  const senderIds = new Set(senderJids.map(jidNum));
  for (const j of senderJids) {
    if (!String(j).endsWith('@lid')) continue;
    try { const pn = await sock.signalRepository?.lidMapping?.getPNForLID?.(j); if (pn) senderIds.add(jidNum(pn)); } catch { /* older Baileys: no table */ }
  }
  const ownerIds = new Set([jidNum(sock.user?.id), jidNum(sock.user?.lid), OWNER_NUMBER, ...OWNER_LIDS].filter(Boolean));
  const adminIds = new Set([OWNER_NUMBER, ...OWNER_LIDS].filter(Boolean));
  const isOwner = !!msg.key.fromMe || [...senderIds].some((n) => ownerIds.has(n));
  const isAdmin = [...senderIds].some((n) => adminIds.has(n));

  if (getMode(sessionId) === 'private' && !isOwner) return; // private mode: only the owner can use the bot

  const cmd = registry.get(command);
  if (cmd?.hidden && !isOwner) return; // hidden commands (the owner menu) do not exist for other people

  react(sock, jid, msg.key, cmd ? (cmd.react || REACTIONS[command] || '✨') : '❔'); // emoji reaction on the command message

  if (cmd?.owner && !isOwner) {
    console.log(`Owner check failed for ${PREFIX}${command}: sender ids [${[...senderIds].join(', ')}], owner ids [${[...ownerIds].join(', ')}]. If one of the sender ids is yours, put it in OWNER_LID.`);
    react(sock, jid, msg.key, '🚫');
    return reply('🚫 This command is for the bot owner only.');
  }
  if (!cmd) return reply(`❔ Unknown command: ${PREFIX}${command}\nSend ${PREFIX}menu to view commands.`);

  // user to act on: @mention, replied-to person, or a number typed after the command
  const targetJid = () => {
    const ctx = unwrapMessage(msg.message).extendedTextMessage?.contextInfo;
    const mentioned = ctx?.mentionedJid?.[0];
    if (mentioned) return mentioned;
    if (ctx?.participant) return ctx.participant;
    const num = (args[0] || '').replace(/\D/g, '');
    if (num.length >= 8) return `${num}@s.whatsapp.net`;
    if (!jid.endsWith('@g.us')) return jid;
    return null;
  };

  try {
    return await cmd.run({ sock, msg, jid, sessionId, args, command, name, footer, reply, isOwner, isAdmin, targetJid });
  } catch (err) {
    console.error(`Command ${command} failed:`, err?.message || err);
    return reply('❌ Something went wrong with that command. Try again.').catch(() => {});
  }
}

setInterval(() => { // keep the cooldown map from growing forever
  const cutoff = Date.now() - 60 * 1000;
  for (const [k, t] of cooldowns) if (t < cutoff) cooldowns.delete(k);
}, 60 * 1000).unref();
